def train_epoch(model, loader, criterion, optimizer, device):
    model.train()
    running_loss = 0.0
    correct = 0
    total = 0

    for images, labels in tqdm(loader, desc='Train'):
        images, labels = images.to(device), labels.to(device)
        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

        running_loss += loss.item()
        _, predicted = outputs.max(1)
        total += labels.size(0)
        correct += predicted.eq(labels).sum().item()

    return running_loss / len(loader), 100. * correct / total


def quick_train_epoch(model, loader, criterion, optimizer, device):
    model.train()
    running_loss = 0.0
    correct = 0
    total = 0

    for images, labels in tqdm(loader, desc='Quick Train'):
        images, labels = images.to(device), labels.to(device)
        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

        running_loss += loss.item()
        _, predicted = outputs.max(1)
        total += labels.size(0)
        correct += predicted.eq(labels).sum().item()

    return running_loss / len(loader), 100. * correct / total

def validate(model, loader, criterion, device):
    model.eval()
    running_loss = 0.0
    correct = 0
    total = 0
    all_preds = []
    all_labels = []

    with torch.no_grad():
        for images, labels in tqdm(loader, desc='Val'):
            images, labels = images.to(device), labels.to(device)
            outputs = model(images)
            loss = criterion(outputs, labels)

            running_loss += loss.item()
            _, predicted = outputs.max(1)
            total += labels.size(0)
            correct += predicted.eq(labels).sum().item()

            all_preds.extend(predicted.cpu().numpy())
            all_labels.extend(labels.cpu().numpy())

    return running_loss / len(loader), 100. * correct / total, all_preds, all_labels

def extract_features(model, dataloader, device):
    model.eval()
    features_list = []

    if config.MODEL_NAME == 'resnet50':
        feature_extractor = nn.Sequential(*list(model.children())[:-1])
    elif config.MODEL_NAME == 'efficientnet_b0':
        feature_extractor = nn.Sequential(*list(model.children())[:-1])
    elif config.MODEL_NAME == 'convnext_tiny':
        # For ConvNeXt, 'features' is the feature extraction part
        feature_extractor = model.features

    feature_extractor = feature_extractor.to(device)

    with torch.no_grad():
        for images, _ in tqdm(dataloader, desc='Extracting features'):
            images = images.to(device)
            features = feature_extractor(images)
            features = features.view(features.size(0), -1)
            features_list.append(features.cpu().numpy())

    return np.vstack(features_list)


