def predict_with_tta(model, image, device, num_augments=5):
    """
    Test-Time Augmentation: Predict on multiple augmented versions
    and average the predictions
    """
    model.eval()

    # Original prediction
    with torch.no_grad():
        image_batch = image.unsqueeze(0).to(device)
        output = model(image_batch)
        predictions = [F.softmax(output, dim=1).cpu()]

    # Augmented predictions
    tta_transforms = [
        transforms.Compose([
            transforms.ToPILImage(),
            transforms.RandomHorizontalFlip(p=1.0),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
        ]),
        transforms.Compose([
            transforms.ToPILImage(),
            transforms.RandomRotation(degrees=5),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
        ]),
        transforms.Compose([
            transforms.ToPILImage(),
            transforms.ColorJitter(brightness=0.1),
            transforms.ToTensor(),
            transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225])
        ]),
    ]

    # Convert tensor back to PIL for augmentation
    image_pil = transforms.ToPILImage()(image)

    for transform in tta_transforms[:num_augments-1]:
        aug_image = transform(image_pil).unsqueeze(0).to(device)
        with torch.no_grad():
            output = model(aug_image)
            predictions.append(F.softmax(output, dim=1).cpu())

    # Average predictions
    avg_prediction = torch.stack(predictions).mean(dim=0)
    _, predicted_class = avg_prediction.max(1)

    return predicted_class.item(), avg_prediction.squeeze()

